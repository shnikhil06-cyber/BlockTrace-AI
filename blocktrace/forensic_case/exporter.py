"""
Forensic Report Exporter for BlockTrace-AI.
Generates comprehensive offline forensic reports in HTML, Markdown, and JSON formats.
"""

from typing import Dict, Any, List, Optional
import json
import pandas as pd
from .case_manager import ForensicCaseManager


class ForensicReportExporter:
    """
    Exports structured forensic case reports for judicial, regulatory, or operational presentation.
    """

    def generate_markdown_report(
        self,
        case: ForensicCaseManager,
        summary_stats: Dict[str, Any],
        flagged_txs: pd.DataFrame,
        explanations: Optional[List[Dict[str, Any]]] = None
    ) -> str:
        """
        Generates clean GFM Markdown forensic audit report.
        """
        exp_lookup = {e["tx_id"]: e for e in (explanations or [])}

        lines = [
            f"# FORENSIC AUDIT DOSSIER: {case.case_title}",
            f"**Case Reference**: `{case.case_id}`  ",
            f"**Investigator**: {case.investigator}  ",
            f"**Organization**: {case.organization}  ",
            f"**Generated**: {case.created_at} (UTC)  ",
            "",
            "---",
            "",
            "## 1. Executive Summary & Telemetry",
            f"- **Total Transactions Analyzed**: {summary_stats.get('total_txs', 0):,}",
            f"- **Network Correlated Transactions**: {summary_stats.get('matched_txs', 0):,} ({summary_stats.get('correlation_rate_pct', 0.0):.1f}%)",
            f"- **Critical Anomalies Flagged**: {summary_stats.get('critical_count', 0):,}",
            f"- **High-Risk Anomalies Flagged**: {summary_stats.get('high_count', 0):,}",
            f"- **Tor / Anonymizer Broadcasts**: {summary_stats.get('tor_proxy_broadcasts', 0):,}",
            f"- **Bulletproof ASN Relays**: {summary_stats.get('bulletproof_broadcasts', 0):,}",
            f"- **Suspicious Bitcoin Volume**: {summary_stats.get('suspicious_volume_btc', 0.0):.4f} BTC",
            "",
            "---",
            "",
            "## 2. Investigator Case Notes & Timeline",
        ]

        for note in case.notes:
            lines.append(f"- {note}")

        lines.extend([
            "",
            "---",
            "",
            "## 3. Flagged Suspicious Transactions & Forensic Attributions",
            "",
            "| Rank | Tx Hash | Volume (BTC) | Fee Rate (sat/vB) | Origin IP | Origin ASN | Risk Tier | Score | Pattern |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
        ])

        top_slice = flagged_txs.head(25)
        for _, row in top_slice.iterrows():
            tx_id = str(row["tx_id"])
            short_tx = f"`{tx_id[:8]}...{tx_id[-6:]}`"
            vol = f"{float(row.get('amount_btc', 0)):.4f}"
            fee_r = f"{float(row.get('fee_rate_sat_vb', 0)):.1f}"
            ip = str(row.get("earliest_ip", "N/A"))
            asn = str(row.get("earliest_asn", "N/A"))
            tier = str(row.get("risk_tier", "NORMAL"))
            score = f"{float(row.get('anomaly_score', 0)):.1f}"
            pattern = str(row.get("forensic_pattern", "N/A")).replace("_", " ")

            lines.append(f"| {row.get('risk_rank', '-')} | {short_tx} | {vol} | {fee_r} | `{ip}` | `{asn}` | **{tier}** | {score} | {pattern} |")

        lines.extend([
            "",
            "---",
            "",
            "## 4. Detailed Explainable Evidence (Top Priority Alerts)",
            ""
        ])

        for _, row in top_slice.head(5).iterrows():
            tx_id = str(row["tx_id"])
            exp = exp_lookup.get(tx_id)
            lines.append(f"### Alert: `{tx_id}`")
            lines.append(f"- **Risk Classification**: **{row.get('risk_tier')}** (Score: {row.get('anomaly_score'):.1f}/100)")
            lines.append(f"- **Identified Signature**: `{row.get('forensic_pattern')}`")
            lines.append(f"- **First Broadcast IP**: `{row.get('earliest_ip')}` ({row.get('earliest_country')}) via ASN `{row.get('earliest_asn')}`")
            if exp:
                lines.append(f"- **Forensic Summary**: {exp.get('summary_text')}")
                lines.append("- **Primary Anomaly Drivers (SHAP Attribution)**:")
                for d in exp.get("top_drivers", []):
                    lines.append(f"  - **{d['label']}**: Observed value `{d['value']:.2f}` (SHAP Impact: `{d['shap_impact']:+.3f}`)")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 5. Forensic Disclaimer & Chain of Custody",
            "> [!NOTE]",
            "> All anomaly scores and pattern tags generated by BlockTrace-AI are investigative risk indicators designed to assist human analysts in prioritizing evidence examination. They do not constitute sole definitive proof of criminal wrongdoing. All processing was executed 100% offline in a secure local environment."
        ])

        return "\n".join(lines)

