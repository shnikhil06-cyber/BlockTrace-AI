    def export_json(
        self,
        case: ForensicCaseManager,
        summary_stats: Dict[str, Any],
        flagged_txs: pd.DataFrame,
        explanations: Optional[List[Dict[str, Any]]] = None
    ) -> str:
        """
        Exports a complete JSON machine-readable archive.
        """
        payload = {
            "case_metadata": case.to_dict(),
            "telemetry_summary": summary_stats,
            "flagged_transactions": flagged_txs.head(50).to_dict(orient="records"),
            "explanations": (explanations or [])[:20]
        }
        return json.dumps(payload, indent=2, default=str)

